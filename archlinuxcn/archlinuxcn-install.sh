#!/usr/bin/env bash

set -e

BASE_URL="https://adrianpriza-ai.github.io/alps-more"
LIB_URL="${BASE_URL}/lib/mirror-probe.sh"

ARCH="$(uname -m)"
TOP=5

TMP="$(mktemp)"
LIB_TMP="$(mktemp)"
TMP_DIR=""

cleanup() {
    rm -f "$TMP" "${TMP}.sorted" "$LIB_TMP"
    if [[ -n "$TMP_DIR" && -d "$TMP_DIR" ]]; then
        rm -rf "$TMP_DIR"
    fi
}
trap cleanup EXIT

curl -fsSL "$LIB_URL" -o "$LIB_TMP"
# shellcheck source=/dev/null
source "$LIB_TMP"

MIRROR_URL="${BASE_URL}/archlinuxcn/archlinuxcn-mirrorlist"

OUTPUT="/etc/pacman.d/archlinuxcn-mirrorlist"

echo "[+] Downloading archlinuxcn mirrorlist..."

curl -fsSL "$MIRROR_URL" -o "$TMP"

echo
echo "[+] Benchmarking mirrors in parallel..."

TMP_DIR="$(mktemp -d)"
count=0

while read -r raw; do
    count=$((count+1))
    (
        test_url="${raw//\$arch/$ARCH}"
        probe_file="$TMP_DIR/probe-$count"

        if speed=$(probe_repo_mirror "${test_url}/archlinuxcn.db" "$probe_file" 50000 gzip); then
            echo "${speed}|${raw}" > "$TMP_DIR/$count"
        fi

        rm -f "$probe_file"
    ) &
done < <(grep '^Server' "$TMP" | sed 's|Server = ||')

wait || true

if ! ls "$TMP_DIR"/* &>/dev/null; then
    echo "[-] Error: No working mirrors found or connection timed out."
    exit 1
fi

cat "$TMP_DIR"/* 2>/dev/null \
| sort -t'|' -k1,1g \
| head -n "$TOP" > "${TMP}.sorted"

rm -rf "$TMP_DIR"
TMP_DIR=""

echo
echo "[+] Best mirrors:"
cat "${TMP}.sorted"

echo
echo "[+] Writing optimized mirrorlist..."

if [[ -f "$OUTPUT" ]]; then
    BACKUP="${OUTPUT}.backup-$(date +%Y%m%d_%H%M%S)"
    echo "[+] Backing up existing mirrorlist to $BACKUP..."
    sudo cp "$OUTPUT" "$BACKUP"
fi

{
    echo "## Generated by ALPS"
    echo

    cut -d'|' -f2 "${TMP}.sorted" \
    | while read -r line; do
        echo "Server = $line"
    done

} | sudo tee "$OUTPUT" >/dev/null

echo
echo "[+] Adding repository to pacman.conf..."

if ! grep -q "^\[archlinuxcn\]" /etc/pacman.conf; then
    {
        echo
        echo "[archlinuxcn]"
        echo "Include = /etc/pacman.d/archlinuxcn-mirrorlist"
    } | sudo tee -a /etc/pacman.conf >/dev/null
fi

echo
echo "[+] Installing archlinuxcn-keyring..."

# farseerfc's key ships with archlinux-keyring but can be marginal trust on new systems
sudo pacman-key --lsign-key "farseerfc@archlinux.org" 2>/dev/null || true

if ! sudo pacman -Sy --noconfirm archlinuxcn-keyring; then
    echo "[+] Retrying after locally trusting farseerfc key..."
    sudo pacman-key --lsign-key "farseerfc@archlinux.org"
    sudo pacman -Sy --noconfirm archlinuxcn-keyring
fi

echo
echo "[+] Syncing pacman..."

sudo pacman -Sy

echo
echo "[+] archlinuxcn setup complete."
