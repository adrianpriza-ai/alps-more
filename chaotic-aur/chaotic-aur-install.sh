#!/usr/bin/env bash

set -e

BASE_URL="https://adrianpriza-ai.github.io/alps-more"
LIB_URL="${BASE_URL}/lib/mirror-probe.sh"

ARCH="$(uname -m)"
TOP=5

TMP="$(mktemp)"
LIB_TMP="$(mktemp)"
TMP_DIR=""

cleanup() {
    rm -f "$TMP" "${TMP}.sorted" "$LIB_TMP"
    if [[ -n "$TMP_DIR" && -d "$TMP_DIR" ]]; then
        rm -rf "$TMP_DIR"
    fi
}
trap cleanup EXIT

curl -fsSL "$LIB_URL" -o "$LIB_TMP"
# shellcheck source=/dev/null
source "$LIB_TMP"

MIRROR_URL="${BASE_URL}/chaotic-aur/chaotic-mirrorlist"

OUTPUT="/etc/pacman.d/chaotic-mirrorlist"

echo "[+] Downloading Chaotic-AUR mirrorlist..."

curl -fsSL "$MIRROR_URL" -o "$TMP"

echo
echo "[+] Benchmarking mirrors in parallel..."

TMP_DIR="$(mktemp -d)"
count=0

while read -r raw; do
    count=$((count+1))
    (
        test_url="${raw//\$arch/$ARCH}"
        test_url="${test_url//\$repo/chaotic-aur}"
        probe_file="$TMP_DIR/probe-$count"

        if speed=$(probe_repo_mirror "${test_url}/chaotic-aur.db" "$probe_file" 50000 zstd); then
            echo "${speed}|${raw}" > "$TMP_DIR/$count"
        fi

        rm -f "$probe_file"
    ) &
done < <(grep '^Server' "$TMP" | sed 's|Server = ||')

wait || true

if ! ls "$TMP_DIR"/* &>/dev/null; then
    echo "[-] Error: No working mirrors found or connection timed out."
    exit 1
fi

cat "$TMP_DIR"/* 2>/dev/null \
| sort -t'|' -k1,1g \
| head -n "$TOP" > "${TMP}.sorted"

rm -rf "$TMP_DIR"
TMP_DIR=""

echo
echo "[+] Best mirrors:"
cat "${TMP}.sorted"

echo
echo "[+] Writing optimized mirrorlist..."

if [[ -f "$OUTPUT" ]]; then
    BACKUP="${OUTPUT}.backup-$(date +%Y%m%d_%H%M%S)"
    echo "[+] Backing up existing mirrorlist to $BACKUP..."
    sudo cp "$OUTPUT" "$BACKUP"
fi

{
    echo "## Generated by ALPS"
    echo

    cut -d'|' -f2 "${TMP}.sorted" \
    | while read -r line; do
        echo "Server = $line"
    done

} | sudo tee "$OUTPUT" >/dev/null

echo
echo "[+] Importing Chaotic-AUR keys..."

sudo pacman-key --recv-keys 3056513887B78AEB --keyserver keyserver.ubuntu.com || \
sudo pacman-key --recv-keys 3056513887B78AEB --keyserver hkps://keyserver.ubuntu.com || \
sudo pacman-key --recv-keys 3056513887B78AEB --keyserver pgp.mit.edu || \
sudo pacman-key --recv-keys 3056513887B78AEB --keyserver keys.openpgp.org

sudo pacman-key --lsign-key 3056513887B78AEB

echo
echo "[+] Installing Chaotic-AUR keyring..."

sudo pacman -U --noconfirm \
    https://cdn-mirror.chaotic.cx/chaotic-aur/chaotic-keyring.pkg.tar.zst \
    https://cdn-mirror.chaotic.cx/chaotic-aur/chaotic-mirrorlist.pkg.tar.zst

echo
echo "[+] Adding repository to pacman.conf..."

if ! grep -q "^\[chaotic-aur\]" /etc/pacman.conf; then
    {
        echo
        echo "[chaotic-aur]"
        echo "Include = /etc/pacman.d/chaotic-mirrorlist"
    } | sudo tee -a /etc/pacman.conf >/dev/null
fi

echo
echo "[+] Syncing pacman..."

sudo pacman -Sy

echo
echo "[+] Chaotic-AUR setup complete."
